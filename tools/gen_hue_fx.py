#!/usr/bin/env python3
"""Generate ultrasync/hue_fx.py from Ultrareader's hue_pro.sh.

The original bash "HUE PRO FX ENGINE" defines 100 effects as shell
functions built from send_hue_cmd '<json>' / sleep N primitives, plus a
`for h in ...` loop form. This parser converts each function into a data
table of steps: {"hue":…, "sat":…, "bri":…, "transitiontime":…, "delay":…}.

SECURITY: only fx_* function bodies and add_fx registration lines are
read. The bridge address / API username lines at the top of the script
are never parsed, copied, or emitted.
"""
import json
import re
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parents[2] / "ultrareader" / "hue_pro.sh"
OUT = Path(__file__).resolve().parents[1] / "ultrasync" / "hue_fx.py"

SEND_RE = re.compile(r"send_hue_cmd\s+'(.*?)'\s*;?\s*(?:sleep\s+([0-9.]+))?", re.S)
LOOP_RE = re.compile(
    r"for\s+(\w+)\s+in\s+([0-9 ]+);\s*do\s+send_hue_cmd\s+'(.*?)'\s*;\s*sleep\s+([0-9.]+)\s*;\s*done",
    re.S,
)
ADD_FX_RE = re.compile(r'add_fx\s+"([^"]+)"\s+"([^"]+)"\s+"(fx_\d+)"')
FUNC_RE = re.compile(r"^(fx_\d+)\(\)\s*\{(.*?)^\}", re.S | re.M)

# Which Hue field each loop variable drives in the original script.
VAR_FIELD = {"h": "hue", "s": "sat", "b": "bri"}


def parse_payload(template: str, var=None, value=None):
    """Turn a bash payload template into a dict, substituting the loop var."""
    tpl = template
    if var is not None:
        tpl = re.sub(r"'\$" + var + r"'", "0", tpl)
    tpl = tpl.replace("'", "")
    try:
        data = json.loads(tpl)
    except Exception:
        return None
    if var is not None and value is not None:
        field = VAR_FIELD.get(var)
        if field:
            data[field] = value
    return data


def parse_function(body: str):
    """Sequential scan: loops and standalone sends, in source order."""
    steps = []
    pos = 0
    while pos < len(body):
        loop = LOOP_RE.search(body, pos)
        send = SEND_RE.search(body, pos)
        if loop and (not send or loop.start() <= send.start()):
            var, values, template, delay = (
                loop.group(1),
                [int(x) for x in loop.group(2).split()],
                loop.group(3),
                float(loop.group(4)),
            )
            for v in values:
                payload = parse_payload(template, var=var, value=v)
                if payload is None:
                    continue
                payload["delay"] = delay
                steps.append(payload)
            pos = loop.end()
        elif send:
            payload = parse_payload(send.group(1))
            if payload is not None:
                payload["delay"] = float(send.group(2)) if send.group(2) else 0.0
                steps.append(payload)
            pos = send.end()
        else:
            break
    return steps


def main():
    text = SRC.read_text()
    registry = {fid: (name, desc) for name, desc, fid in ADD_FX_RE.findall(text)}
    effects = []
    for fid, body in FUNC_RE.findall(text):
        name, desc = registry.get(fid, (fid, ""))
        steps = parse_function(body)
        effects.append({"id": fid, "name": name, "description": desc, "steps": steps})
    effects.sort(key=lambda e: int(e["id"].split("_")[1]))
    parsed = sum(1 for e in effects if e["steps"])

    with open(OUT, "w") as f:
        f.write('"""Hue FX library — ported from Ultrareader\'s hue_pro.sh bash engine.\n\n')
        f.write("Each effect is a list of Hue state steps (hue/sat/bri/transitiontime)\n")
        f.write("with a per-step delay in seconds. Generated by tools/gen_hue_fx.py.\n")
        f.write('Contains NO bridge credentials — those come from config/env only.\n"""\n\n')
        f.write("FX = ")
        f.write(repr(effects))
        f.write("\n")
    print(f"wrote {OUT}: {len(effects)} effects, {parsed} with parsed steps")


if __name__ == "__main__":
    sys.exit(main())
