"""Philips Hue integration — the two parents' bash engine, ported to Python.

Both repos shipped a byte-identical 635-line bash script (hue_pro.sh /
hue_sync.sh) with a hardcoded bridge address and API key. UltraSync
replaces it once, in Python:
- Bridge IP + API key come from the unified config or HUE_BRIDGE_IP /
  HUE_API_KEY env vars. No credentials exist in this codebase.
- The 100 bash lighting effects are data (see hue_fx.py, generated by
  tools/gen_hue_fx.py) played by HueFXPlayer.
- Condition sync maps live weather/Kp/theme state to light states.
"""
import json
import ssl
import threading
import time
import urllib.request
from typing import Dict, List, Optional

from .hue_fx import FX
from .themes import hex_to_hue

_SSL_CTX = ssl._create_unverified_context()  # bridges use self-signed certs (bash used curl -k)


class HueClient:
    def __init__(self, bridge_ip: str = None, api_key: str = None, lights=None):
        self.bridge_ip = bridge_ip
        self.api_key = api_key
        self.lights = lights or [1, 6]

    @property
    def configured(self) -> bool:
        return bool(self.bridge_ip and self.api_key)

    def _request(self, method: str, path: str, payload: dict = None, timeout=5):
        if not self.configured:
            return None
        url = f"https://{self.bridge_ip}/api/{self.api_key}{path}"
        data = json.dumps(payload).encode() if payload is not None else None
        req = urllib.request.Request(url, data=data, method=method,
                                     headers={"Content-Type": "application/json"})
        try:
            with urllib.request.urlopen(req, timeout=timeout, context=_SSL_CTX) as resp:
                return json.loads(resp.read().decode("utf-8"))
        except Exception:
            return None

    def get_lights(self) -> Dict:
        out = {}
        data = self._request("GET", "/lights")
        if isinstance(data, dict):
            for lid, info in data.items():
                state = info.get("state", {})
                out[str(lid)] = {
                    "id": int(lid),
                    "name": info.get("name", f"Light {lid}"),
                    "on": bool(state.get("on")),
                    "bri": state.get("bri"),
                    "hue": state.get("hue"),
                    "sat": state.get("sat"),
                    "reachable": state.get("reachable", True),
                }
        return out

    def set_state(self, light_id: int, payload: dict) -> bool:
        result = self._request("PUT", f"/lights/{light_id}/state", payload)
        return isinstance(result, list) and any("success" in r for r in result if isinstance(r, dict))

    def set_all(self, payload: dict) -> int:
        return sum(1 for lid in self.lights if self.set_state(lid, payload))


def condition_payload(weather_code, kp, theme: dict) -> dict:
    """Light state for current conditions (SolarSync's hue triggers, extended).

    Storm geomagnetics win over weather; otherwise the theme's primary
    color is warmed/cooled by the sky condition.
    """
    try:
        kp = float(kp) if kp is not None else 0.0
    except (TypeError, ValueError):
        kp = 0.0
    if kp >= 7:
        return {"on": True, "hue": 0, "sat": 254, "bri": 220, "transitiontime": 10}      # red alert
    if kp >= 5:
        return {"on": True, "hue": 8000, "sat": 254, "bri": 200, "transitiontime": 10}   # orange
    code = weather_code if isinstance(weather_code, int) else -1
    if code in (95, 96, 99):       # thunderstorm
        return {"on": True, "hue": 47000, "sat": 200, "bri": 210, "transitiontime": 10}
    if code in (61, 63, 65, 80, 81, 82, 51, 53, 55):  # rain
        return {"on": True, "hue": 42000, "sat": 180, "bri": 170, "transitiontime": 10}
    if code in (71, 73, 75, 77, 85, 86):              # snow
        return {"on": True, "hue": 38000, "sat": 60, "bri": 220, "transitiontime": 10}
    base = hex_to_hue(theme.get("primary", "#00ff41"), bri=190)
    base.update({"on": True, "transitiontime": 10})
    return base


class HueFXPlayer:
    """Plays hue_fx step tables on a background thread (bash start_fx/stop_fx)."""

    def __init__(self, client: HueClient):
        self.client = client
        self._thread: Optional[threading.Thread] = None
        self._stop = threading.Event()
        self.current: Optional[Dict] = None

    def list_effects(self) -> List[Dict]:
        return [{"index": i, "id": fx["id"], "name": fx["name"],
                 "description": fx["description"], "steps": len(fx["steps"])}
                for i, fx in enumerate(FX)]

    def play(self, index: int) -> bool:
        if not self.client.configured or not (0 <= index < len(FX)):
            return False
        self.stop()
        fx = FX[index]
        self.current = {"index": index, "name": fx["name"]}
        self._stop.clear()

        def _run():
            while not self._stop.is_set():
                for step in fx["steps"]:
                    if self._stop.is_set():
                        break
                    payload = {k: v for k, v in step.items() if k != "delay"}
                    self.client.set_all(payload)
                    if self._stop.wait(timeout=step.get("delay", 0.5)):
                        break

        self._thread = threading.Thread(target=_run, daemon=True)
        self._thread.start()
        return True

    def stop(self):
        self._stop.set()
        if self._thread and self._thread.is_alive():
            self._thread.join(timeout=1.0)
        self._thread = None
        self.current = None

    def status(self) -> Dict:
        return {"playing": self.current}

    # -- bash parity: direct effect step application ----------------------
    @staticmethod
    def apply_step(client: HueClient, step: Dict) -> int:
        payload = {k: v for k, v in step.items() if k != "delay"}
        return client.set_all(payload)
